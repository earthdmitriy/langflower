/**
 * Flat YAML frontmatter for docs-gen. Scalars and string lists only.
 * Unparseable input returns ok: false. It does not throw.
 */

export const GENERATED_MARKER = '<!-- generated by docs-gen; do not edit -->';

export const REGISTRY_START = '<!-- package-local-registry:start -->';

export const REGISTRY_END = '<!-- package-local-registry:end -->';

const unquote = (value) => {
	const trimmed = value.trim();
	if (
		(trimmed.startsWith('"') && trimmed.endsWith('"')) ||
		(trimmed.startsWith("'") && trimmed.endsWith("'"))
	) {
		return trimmed.length >= 2 ? trimmed.slice(1, -1) : trimmed;
	}
	return trimmed;
};

const parseInlineList = (value) => {
	const trimmed = value.trim();
	if (!trimmed.startsWith('[') || !trimmed.endsWith(']')) {
		return null;
	}
	const inner = trimmed.slice(1, -1).trim();
	if (inner === '') {
		return [];
	}
	const parts = [];
	let current = '';
	let quote = null;
	for (const char of inner) {
		if (quote) {
			if (char === quote) {
				quote = null;
				continue;
			}
			current += char;
			continue;
		}
		if (char === '"' || char === "'") {
			quote = char;
			continue;
		}
		if (char === ',') {
			parts.push(current.trim());
			current = '';
			continue;
		}
		current += char;
	}
	if (quote) {
		return null;
	}
	parts.push(current.trim());
	return parts.filter((part) => part.length > 0);
};

export const parseFrontmatter = (text) => {
	const stripped = text.replace(/^\uFEFF/, '');
	if (!stripped.startsWith('---')) {
		return { ok: false, body: stripped, data: {} };
	}
	const lines = stripped.split(/\r?\n/);
	if (lines[0] !== '---') {
		return { ok: false, body: stripped, data: {} };
	}
	let end = -1;
	for (let index = 1; index < lines.length; index += 1) {
		if (lines[index] === '---') {
			end = index;
			break;
		}
	}
	if (end < 0) {
		return { ok: false, body: stripped, data: {} };
	}
	const data = {};
	let listKey = null;
	for (let index = 1; index < end; index += 1) {
		const line = lines[index] ?? '';
		if (line.trim() === '' || /^[ \t]*#/.test(line)) {
			continue;
		}
		const item = /^[ \t]*-[ \t]+(.*)$/.exec(line);
		if (item) {
			if (listKey === null || !Array.isArray(data[listKey])) {
				return { ok: false, body: stripped, data: {} };
			}
			data[listKey].push(unquote(item[1] ?? ''));
			continue;
		}
		const pair = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
		if (!pair) {
			return { ok: false, body: stripped, data: {} };
		}
		const key = pair[1];
		const raw = pair[2] ?? '';
		if (raw.trim() === '') {
			data[key] = [];
			listKey = key;
			continue;
		}
		if (raw.trim().startsWith('[')) {
			const inline = parseInlineList(raw);
			if (inline === null) {
				return { ok: false, body: stripped, data: {} };
			}
			data[key] = inline;
			listKey = null;
			continue;
		}
		data[key] = unquote(raw);
		listKey = null;
	}
	return {
		ok: true,
		data,
		body: lines.slice(end + 1).join('\n'),
	};
};

export const firstHeading = (text) => {
	const parsed = parseFrontmatter(text);
	const body = parsed.ok ? parsed.body : text;
	const match = /^#{1,6}[ \t]+(.+?)[ \t]*$/m.exec(body);
	return match ? (match[1] ?? '').trim() : '';
};

export const isGenerated = (text) => {
	const line = text.replace(/^\uFEFF/, '').split(/\r?\n/, 1)[0] ?? '';
	return line.trim() === GENERATED_MARKER;
};
