/**
 * Repo scan for docs-boundaries: markdown, flat YAML frontmatter,
 * GitHub-style heading slugs, and relative links.
 * Unparseable frontmatter is a result, never a throw.
 */

import { spawnSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

export const GENERATED_MARKER = '<!-- generated by docs-gen; do not edit -->';

const SKIP_DIRS = new Set(['node_modules', 'dist', '.git', 'vendor']);

export type FrontmatterValue = string | readonly string[];

export type FrontmatterParse =
	| {
			readonly ok: true;
			readonly data: Readonly<Record<string, FrontmatterValue>>;
			readonly body: string;
	  }
	| {
			readonly ok: false;
			readonly message: string;
			readonly line: number;
	  };

export type LinkKind = 'relative' | 'anchor' | 'external' | 'absolute';

export type MarkdownLink = {
	readonly target: string;
	readonly pathPart: string;
	readonly hash: string;
	readonly resolved: string | null;
	readonly kind: LinkKind;
};

export type MarkdownFile = {
	readonly path: string;
	readonly text: string;
	readonly bytes: number;
	readonly generated: boolean;
	readonly frontmatter: FrontmatterParse;
	readonly links: readonly MarkdownLink[];
	readonly anchors: readonly string[];
};

export type RepoSnapshot = {
	readonly root: string;
	readonly files: readonly string[];
	readonly markdown: readonly MarkdownFile[];
	readonly markdownByPath: ReadonlyMap<string, MarkdownFile>;
};

const snapshots = new Map<string, RepoSnapshot>();

export const toPosix = (value: string): string => value.replace(/\\/g, '/');

export const samePath = (left: string, right: string): boolean =>
	path.resolve(left).replace(/\\/g, '/').toLowerCase() ===
	path.resolve(right).replace(/\\/g, '/').toLowerCase();

const gitOk = (
	root: string,
	args: readonly string[],
): { readonly status: number; readonly stdout: string } | null => {
	const result = spawnSync('git', ['-C', root, ...args], {
		encoding: 'utf8',
		windowsHide: true,
		maxBuffer: 16 * 1024 * 1024,
	});
	if (result.error) {
		return null;
	}
	return {
		status: result.status ?? 1,
		stdout: result.stdout ?? '',
	};
};

const walkFiles = (root: string): readonly string[] => {
	const out: string[] = [];
	const visit = (abs: string): void => {
		let entries;
		try {
			entries = readdirSync(abs, { withFileTypes: true });
		} catch {
			return;
		}
		for (const entry of entries) {
			if (SKIP_DIRS.has(entry.name)) {
				continue;
			}
			const full = path.join(abs, entry.name);
			if (entry.isDirectory()) {
				visit(full);
				continue;
			}
			if (!entry.isFile()) {
				continue;
			}
			out.push(toPosix(path.relative(root, full)));
		}
	};
	visit(root);
	return out.sort();
};

/** Tracked files plus untracked non-ignored files. Walks when git is absent. */
export const listRepoFiles = (root: string): readonly string[] => {
	const top = gitOk(root, ['rev-parse', '--show-toplevel']);
	if (
		top === null ||
		top.status !== 0 ||
		!samePath(top.stdout.trim(), root)
	) {
		return walkFiles(root);
	}
	const tracked = gitOk(root, ['ls-files']);
	if (tracked === null || tracked.status !== 0) {
		return walkFiles(root);
	}
	const others = gitOk(root, ['ls-files', '--others', '--exclude-standard']);
	const combined = `${tracked.stdout}\n${others?.stdout ?? ''}`;
	const files = new Set<string>();
	for (const line of combined.split(/\r?\n/)) {
		const rel = toPosix(line.trim());
		if (rel.length > 0) {
			files.add(rel);
		}
	}
	return [...files].sort();
};

const unquote = (value: string): string => {
	const trimmed = value.trim();
	if (
		(trimmed.startsWith('"') && trimmed.endsWith('"')) ||
		(trimmed.startsWith("'") && trimmed.endsWith("'"))
	) {
		if (trimmed.length >= 2) {
			return trimmed.slice(1, -1);
		}
	}
	return trimmed;
};

const parseInlineList = (value: string): readonly string[] | null => {
	const trimmed = value.trim();
	if (!trimmed.startsWith('[')) {
		return null;
	}
	if (!trimmed.endsWith(']')) {
		return null;
	}
	const inner = trimmed.slice(1, -1).trim();
	if (inner === '') {
		return [];
	}
	const parts: string[] = [];
	let current = '';
	let quote: '"' | "'" | null = null;
	for (let index = 0; index < inner.length; index += 1) {
		const char = inner[index] ?? '';
		if (quote !== null) {
			if (char === quote) {
				quote = null;
				continue;
			}
			current += char;
			continue;
		}
		if (char === '"' || char === "'") {
			quote = char;
			continue;
		}
		if (char === ',') {
			parts.push(current.trim());
			current = '';
			continue;
		}
		current += char;
	}
	if (quote !== null) {
		return null;
	}
	parts.push(current.trim());
	return parts.filter((part) => part.length > 0);
};

const parseFrontmatterInner = (text: string): FrontmatterParse => {
	const stripped = text.replace(/^\uFEFF/, '');
	if (!stripped.startsWith('---')) {
		return { ok: false, message: 'missing frontmatter', line: 1 };
	}
	const lines = stripped.split(/\r?\n/);
	if ((lines[0] ?? '') !== '---') {
		return {
			ok: false,
			message: 'opening frontmatter fence must be ---',
			line: 1,
		};
	}
	let end = -1;
	for (let index = 1; index < lines.length; index += 1) {
		if (lines[index] === '---') {
			end = index;
			break;
		}
	}
	if (end < 0) {
		return { ok: false, message: 'unclosed frontmatter', line: 1 };
	}
	const data: Record<string, string | string[]> = {};
	let listKey: string | null = null;
	for (let index = 1; index < end; index += 1) {
		const line = lines[index] ?? '';
		const lineNo = index + 1;
		if (line.trim() === '' || /^[ \t]*#/.test(line)) {
			continue;
		}
		const item = /^[ \t]*-[ \t]+(.*)$/.exec(line);
		if (item) {
			if (listKey === null) {
				return {
					ok: false,
					message: 'list item without a key',
					line: lineNo,
				};
			}
			const bucket = data[listKey];
			if (!Array.isArray(bucket)) {
				return {
					ok: false,
					message: `list item under scalar key ${listKey}`,
					line: lineNo,
				};
			}
			bucket.push(unquote(item[1] ?? ''));
			continue;
		}
		const pair = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line);
		if (!pair) {
			return {
				ok: false,
				message: 'unparseable frontmatter line',
				line: lineNo,
			};
		}
		const key = pair[1] ?? '';
		const raw = pair[2] ?? '';
		if (Object.prototype.hasOwnProperty.call(data, key)) {
			return {
				ok: false,
				message: `duplicate frontmatter key ${key}`,
				line: lineNo,
			};
		}
		if (raw.trim() === '') {
			data[key] = [];
			listKey = key;
			continue;
		}
		if (raw.trim().startsWith('[')) {
			const inline = parseInlineList(raw);
			if (inline === null) {
				return {
					ok: false,
					message: `unparseable list for ${key}`,
					line: lineNo,
				};
			}
			data[key] = [...inline];
			listKey = null;
			continue;
		}
		data[key] = unquote(raw);
		listKey = null;
	}
	const frozen: Record<string, FrontmatterValue> = {};
	for (const [key, value] of Object.entries(data)) {
		frozen[key] = Array.isArray(value) ? [...value] : value;
	}
	return {
		ok: true,
		data: frozen,
		body: lines.slice(end + 1).join('\n'),
	};
};

export const parseFrontmatter = (text: string): FrontmatterParse => {
	try {
		return parseFrontmatterInner(text);
	} catch (error) {
		const message =
			error instanceof Error ? error.message : 'unparseable frontmatter';
		return { ok: false, message, line: 1 };
	}
};

export const isGeneratedMarkdown = (text: string): boolean => {
	const stripped = text.replace(/^\uFEFF/, '');
	const line = stripped.split(/\r?\n/, 1)[0] ?? '';
	return line.trim() === GENERATED_MARKER;
};

/** GitHub heading slug. Punctuation drops; each space becomes a hyphen. */
export const headingSlug = (text: string): string => {
	const plain = text
		.replace(/<[^>]*>/g, '')
		.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
		.replace(/`([^`]*)`/g, '$1')
		.trim()
		.toLowerCase();
	return plain
		.replace(/[^\p{L}\p{M}\p{N}\p{Pc}\- ]/gu, '')
		.replace(/ /g, '-');
};

const stripFences = (text: string): string =>
	text.replace(/```[\s\S]*?```/g, '').replace(/~~~[\s\S]*?~~~/g, '');

export const extractAnchors = (text: string): readonly string[] => {
	const source = stripFences(text);
	const lines = source.split(/\r?\n/);
	const seen = new Map<string, number>();
	const slugs: string[] = [];
	const take = (slug: string): void => {
		const count = seen.get(slug) ?? 0;
		seen.set(slug, count + 1);
		slugs.push(count === 0 ? slug : `${slug}-${count}`);
	};
	for (let index = 0; index < lines.length; index += 1) {
		const line = lines[index] ?? '';
		const atx = /^(#{1,6})[ \t]+(.+?)[ \t]*#*[ \t]*$/.exec(line);
		if (atx) {
			take(headingSlug(atx[2] ?? ''));
			continue;
		}
		const next = lines[index + 1] ?? '';
		if (
			line.trim() !== '' &&
			next.trim().length >= 3 &&
			/^(?:=+|-+)$/.test(next.trim())
		) {
			take(headingSlug(line.trim()));
			index += 1;
		}
	}
	const ids: string[] = [];
	for (const match of source.matchAll(/\sid=["']([^"']+)["']/gi)) {
		const id = match[1];
		if (id) {
			ids.push(id);
		}
	}
	for (const match of source.matchAll(/\{#([A-Za-z0-9_-]+)\}/g)) {
		const id = match[1];
		if (id) {
			ids.push(id);
		}
	}
	return [...new Set([...slugs, ...ids])];
};

export const anchorResolves = (
	hash: string,
	anchors: readonly string[],
): boolean => {
	if (hash === '') {
		return true;
	}
	let decoded = hash;
	try {
		decoded = decodeURIComponent(hash);
	} catch {
		decoded = hash;
	}
	const known = new Set(anchors);
	if (known.has(decoded) || known.has(decoded.toLowerCase())) {
		return true;
	}
	return known.has(headingSlug(decoded));
};

const decodePath = (value: string): string => {
	try {
		return decodeURIComponent(value);
	} catch {
		return value;
	}
};

export const extractLinks = (
	filePath: string,
	text: string,
): readonly MarkdownLink[] => {
	const dir = path.posix.dirname(filePath);
	const links: MarkdownLink[] = [];
	const pattern = /\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g;
	for (const match of text.matchAll(pattern)) {
		const target = match[1] ?? '';
		const hashAt = target.indexOf('#');
		const hash = hashAt === -1 ? '' : target.slice(hashAt + 1);
		const rawPath = hashAt === -1 ? target : target.slice(0, hashAt);
		if (rawPath === '') {
			links.push({
				target,
				pathPart: '',
				hash,
				resolved: filePath,
				kind: 'anchor',
			});
			continue;
		}
		if (/^[a-z][a-z0-9+.-]*:/i.test(rawPath)) {
			links.push({
				target,
				pathPart: rawPath,
				hash,
				resolved: null,
				kind: 'external',
			});
			continue;
		}
		if (rawPath.startsWith('/')) {
			links.push({
				target,
				pathPart: rawPath,
				hash,
				resolved: null,
				kind: 'absolute',
			});
			continue;
		}
		const pathPart = decodePath(rawPath);
		const resolved = path.posix.normalize(path.posix.join(dir, pathPart));
		links.push({
			target,
			pathPart,
			hash,
			resolved,
			kind: 'relative',
		});
	}
	return links;
};

export const compileGlob = (glob: string): RegExp => {
	const source = toPosix(glob).replace(/^\.\//, '');
	let pattern = '';
	for (let index = 0; index < source.length; index += 1) {
		const char = source[index] ?? '';
		const next = source[index + 1];
		if (char === '*' && next === '*') {
			if (source[index + 2] === '/') {
				pattern += '(?:[^/]*/)*';
				index += 2;
				continue;
			}
			pattern += '.*';
			index += 1;
			continue;
		}
		if (char === '*') {
			pattern += '[^/]*';
			continue;
		}
		if (char === '?') {
			pattern += '[^/]';
			continue;
		}
		if (/[\\^$+?.()|[\]{}]/.test(char)) {
			pattern += `\\${char}`;
			continue;
		}
		pattern += char;
	}
	return new RegExp(`^${pattern}$`);
};

export const globMatches = (glob: string, relPath: string): boolean =>
	compileGlob(glob).test(toPosix(relPath));

export const hasToken = (text: string, token: string): boolean => {
	const escaped = token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
	return new RegExp(
		`(?:^|[^A-Za-z0-9_-])${escaped}(?:[^A-Za-z0-9_-]|$)`,
	).test(text);
};

const readUtf8 = (abs: string): string | null => {
	try {
		return readFileSync(abs, 'utf8');
	} catch {
		return null;
	}
};

const loadMarkdown = (root: string, rel: string): MarkdownFile | null => {
	if (!rel.endsWith('.md') && !rel.endsWith('.mdc')) {
		return null;
	}
	const text = readUtf8(path.join(root, rel));
	if (text === null) {
		return null;
	}
	const frontmatter = parseFrontmatter(text);
	const headingSource = frontmatter.ok ? frontmatter.body : text;
	return {
		path: rel,
		text,
		bytes: Buffer.byteLength(text, 'utf8'),
		generated: isGeneratedMarkdown(text),
		frontmatter,
		links: extractLinks(rel, text),
		anchors: extractAnchors(headingSource),
	};
};

export const snapshot = (root: string): RepoSnapshot => {
	const key = path.resolve(root);
	const cached = snapshots.get(key);
	if (cached) {
		return cached;
	}
	const files = listRepoFiles(key);
	const markdown: MarkdownFile[] = [];
	const markdownByPath = new Map<string, MarkdownFile>();
	for (const rel of files) {
		const file = loadMarkdown(key, rel);
		if (file === null) {
			continue;
		}
		markdown.push(file);
		markdownByPath.set(file.path, file);
	}
	const built: RepoSnapshot = {
		root: key,
		files,
		markdown,
		markdownByPath,
	};
	snapshots.set(key, built);
	return built;
};

export const fileExists = (root: string, rel: string): boolean => {
	try {
		statSync(path.join(root, rel));
		return true;
	} catch {
		return false;
	}
};

export const readRepoText = (root: string, rel: string): string | null =>
	readUtf8(path.join(root, rel));

/**
 * Drop fenced code so example paths are not citations.
 * An unclosed fence blanks the rest of the file.
 */
const stripFencedBlocks = (text: string): string => {
	const lines = text.split(/\r?\n/);
	const kept: string[] = [];
	let fenced = false;
	for (const line of lines) {
		if (/^ {0,3}(?:```+|~~~+)/.test(line)) {
			fenced = !fenced;
			kept.push('');
			continue;
		}
		kept.push(fenced ? '' : line);
	}
	return kept.join('\n');
};

/**
 * `docs/...` citations. A slash or word char before `docs/` is not a cite.
 * Fenced examples are ignored. A path containing `NNN` or `<` is a template,
 * not a file.
 */
export const extractDocCitations = (text: string): readonly string[] => {
	const found = new Set<string>();
	const pattern = /(?:^|(?<=[^A-Za-z0-9_./-]))docs\/[A-Za-z0-9_./<>-]+/g;
	for (const match of stripFencedBlocks(text).matchAll(pattern)) {
		let cited = match[0] ?? '';
		while (cited.endsWith('.') || cited.endsWith('/')) {
			cited = cited.slice(0, -1);
		}
		if (
			cited.includes('NNN') ||
			cited.includes('<') ||
			cited.includes('>')
		) {
			continue;
		}
		if (cited.startsWith('docs/') && cited.length > 'docs/'.length) {
			found.add(cited);
		}
	}
	return [...found];
};
